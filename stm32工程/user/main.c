/*******************************************************************************
 * 模块名称：主程序模块
 * 所属工程：智能车（STM32F103 + 板载 LED / 蜂鸣器 / 按键）
 * 模块职责：工程入口，完成系统级初始化后进入主循环，循环执行 LED 流水灯演示
 * 说明：本模块为自研代码，逻辑未改动，仅补充中文注释便于阅读维护
 ******************************************************************************/
#include "main.h"

/**
 * 函数名：main
 * 描述  ：程序入口：初始化 SysTick 时基与 LED 引脚，随后进入主循环执行流水灯
 * 输入  ：无
 * 输出  ：int（标准 C 入口返回值；嵌入式环境下不会返回）
 * 说明  ：① JTAG_SW_Config() 关闭 JTAG，释放 PA15/PB3/PB4 供普通 IO 使用；
 *         ② Systick_Init(72000) 配置 SysTick，72MHz 时钟下约 1ms 触发一次中断；
 *         ③ while(1) 中以 LED_Water() 配合 Delay_ms(500) 实现 0.5s 间隔流水灯
 */
int main(void)
{
	JTAG_SW_Config();       // 关闭 JTAG，释放 PA15/PB3/PB4 给普通 IO 使用
	Systick_Init(72000);    // 初始化 SysTick：重装载值 72000，72MHz 时钟下约 1ms 触发一次
	//初始化
	LED_Config();           // 初始化 LED 引脚（PC0/PC1/PC2 推挽输出）
	
	
	
	while(1)                // 主循环：持续执行流水灯逻辑
	{
		LED_Water();        // 流水灯：依次点亮 LED1 -> LED2 -> LED3，循环往复
		Delay_ms(500);      // 软件延时 500ms，控制流水灯切换节奏
	}
	
}
